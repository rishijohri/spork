export interface IconProps extends Omit<SVGProps<SVGSVGElement>, "name"> {
  /** The icon to render; unknown names fall back to a neutral circle. */
  name: IconName | string;
  /** Pixel size (width = height). Default 16. */
  size?: number;
}

/** Render a named line icon. Inherits color via `currentColor`. */
export function Icon({
  name,
  size = 16,
  className,
  strokeWidth = 2,
  ...rest
}: IconProps): JSX.Element {
  const content = ICONS[name as IconName] ?? ICONS.circle;
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden="true"
      focusable="false"
      {...rest}
    >
      {content}
    </svg>
  );
}

/** Whether a name resolves to a real icon (not the fallback). */
export function hasIcon(name: string): name is IconName {
  return name in ICONS;
}
